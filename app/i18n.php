function app_language() {
	$lang = strtolower($_GET['lang'] ?? '');

	if ($lang === '') {
		$lang = strtolower(substr($_SERVER['HTTP_ACCEPT_LANGUAGE'] ?? 'en', 0, 2));
	}

	return in_array($lang, ['en', 'nl', 'fr', 'de', 'es'], true) ? $lang : 'en';
}

